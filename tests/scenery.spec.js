const { test, expect } = require('./fixtures.cjs');
test('30 seconds without activity shows scenery; OK wakes once without launching and focus is restored', async ({ page }) => {
  await page.clock.install();
  await page.emulateMedia({reducedMotion:'reduce'});
  await page.addInitScript(() => { window.calls = []; window.PalmServiceBridge = function () { this.call = (uri, body) => { calls.push(JSON.parse(body)); this.onservicecallback('{"returnValue":true}'); }; }; });
  await page.goto('/');
  await expect(page.locator('#wallpapers')).toHaveAttribute('data-scene','blue-ridges.jpg');
  await page.clock.pauseAt(new Date(Date.now() + 1000));
  await page.evaluate(() => document.dispatchEvent(new KeyboardEvent('keyup', {keyCode:16,bubbles:true})));
  await page.clock.fastForward(29900); await expect(page.locator('#screen')).not.toHaveClass(/scenery-mode/);
  await page.keyboard.press('ArrowRight');
  await page.clock.fastForward(29900); await expect(page.locator('#screen')).not.toHaveClass(/scenery-mode/);
  await page.clock.fastForward(150); await expect(page.locator('#screen')).toHaveClass(/scenery-mode/);
  await expect(page.locator('.apps-section')).toBeHidden(); await expect(page.locator('#clock')).toBeVisible();
  await expect(page.locator('#wallpapers img').last()).toHaveClass(/is-visible/);
  await page.screenshot({path:'artifacts/scenery-mode-preview.png'});
  await page.keyboard.down('Enter'); await page.clock.fastForward(750); await page.keyboard.up('Enter');
  await expect(page.locator('#screen')).not.toHaveClass(/scenery-mode/);
  await expect(page.getByRole('button',{name:'Stremio',exact:true})).toBeFocused();
  expect(await page.evaluate(()=>calls)).toEqual([]); await expect(page.locator('.reordering')).toHaveCount(0);
  await page.keyboard.press('Enter'); expect(await page.evaluate(()=>calls)).toEqual([{id:'io.strem.tv',params:{}}]);
});
test('pointer click wakes without activating a tile; cursor movement resets inactivity', async ({ page }) => {
  await page.clock.install(); await page.goto('/');
  await page.clock.fastForward(30100); await expect(page.locator('#screen')).toHaveClass(/scenery-mode/);
  await page.locator('#scenery-overlay').dispatchEvent('pointerdown',{pointerType:'mouse'});
  await page.locator('#scene-button').dispatchEvent('click');
  await expect(page.locator('#scene-button')).not.toHaveAttribute('aria-busy','true');
  await expect(page.locator('#toast')).not.toHaveClass(/visible/);
  await page.clock.fastForward(29000); await page.mouse.move(150,200); await page.clock.fastForward(29000);
  await expect(page.locator('#screen')).not.toHaveClass(/scenery-mode/);
  await page.clock.fastForward(1100); await expect(page.locator('#screen')).toHaveClass(/scenery-mode/);
});
test('popups and hidden apps pause scenery; its switch persists and leaves backgrounds untouched', async ({ page }) => {
  await page.clock.install(); await page.goto('/');
  await page.getByRole('button',{name:'Open Settings'}).click(); await page.clock.fastForward(60000);
  await expect(page.locator('#screen')).not.toHaveClass(/scenery-mode/);
  await page.getByRole('tab',{name:'Scenery'}).click();
  const setting=page.getByRole('switch',{name:/Scenery mode/}); await expect(setting).toHaveAttribute('aria-checked','true');
  await setting.click(); await expect(setting).toHaveAttribute('aria-checked','false');
  await page.getByRole('button',{name:'Done',exact:true}).click(); await page.clock.fastForward(60000);
  await expect(page.locator('#screen')).not.toHaveClass(/scenery-mode/); await page.reload();
  expect(await page.evaluate(()=>QUIET_SCENERY.enabled())).toBe(false); expect(await page.evaluate(()=>QUIET_WALLPAPERS.mode())).toBe('rotate');
  await page.evaluate(()=>QUIET_SCENERY.toggle());
  await page.evaluate(()=>{Object.defineProperty(document,'hidden',{configurable:true,value:true});document.dispatchEvent(new Event('visibilitychange'));});
  await page.clock.fastForward(60000); await expect(page.locator('#screen')).not.toHaveClass(/scenery-mode/);
  await page.evaluate(()=>{Object.defineProperty(document,'hidden',{configurable:true,value:false});document.dispatchEvent(new Event('visibilitychange'));});
  await page.clock.fastForward(29900); await expect(page.locator('#screen')).not.toHaveClass(/scenery-mode/);
  await page.clock.fastForward(200); await expect(page.locator('#screen')).toHaveClass(/scenery-mode/);
});
